#!/usr/bin/env python3
"""Generate manuscript inputs so the LaTeX contains no hand-typed results (ABAI L007).

  manuscript/numbers.tex      \\newcommand macros for every number quoted in the text,
                              read from results/tables and data/ (generated by the export)
  manuscript/references.bib   from data/params/references.csv (Crossref-verified)

Run after `npm run export` and python/make_figures.py.
"""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T = ROOT / "results" / "tables"
M = ROOT / "manuscript"
M.mkdir(exist_ok=True)


def rows(name):
    with (T / name).open() as fh:
        return list(csv.DictReader(fh))


def num(x, nd=1):
    if x in ("", None):
        return "n.a."
    return f"{float(x):.{nd}f}"


macros: dict[str, str] = {}


def put(name: str, value: str):
    assert re.fullmatch(r"[A-Za-z]+", name), name
    macros[name] = value


summ = {r["scenario"]: r for r in rows("scenario_summary.csv")}
words = {"ground_light": "Ground", "ground_dark": "GroundDark", "bric_pdfu": "Bric", "bric_pdfu_1g": "BricOneG", "bric_led": "BricLed",
         "cara": "Cara", "aph": "Aph", "emcs_0g": "EmcsZero", "emcs_1g": "EmcsOne", "leaf_gbc1": "Gbc", "ground_exploration": "Explo",
         "ground_staged": "Staged", "ground_counterfactual": "Counter", "bric_exploration": "BricExplo", "ground_hypoxia_10pct": "HypoTen",
         "ground_hypoxia_5pct": "HypoFive", "deep_space_spe": "Spe", "deep_space_spe_hyp": "SpeHyp", "ethylene_10ppm_dark": "EthTen",
         "mir_cabin_ethylene": "Mir", "emcs_0.166g": "EmcsLunar", "emcs_0.38g": "EmcsMars"}
fields = {"testa_rupture_h": "TR", "endosperm_rupture_h": "ER", "cot_emerged_h": "CotOut", "cot_open_h": "CotOpen",
          "min_o2_surface_kpa": "OSurf", "min_o2_core_kpa": "OCore", "peak_eth_headspace_ppb": "EthHs", "peak_eth_internal_ppb": "EthInt",
          "hypoxic_frac_24h": "HypoFrac",
          "root_len_120h_um": "Root", "hyp_len_120h_um": "Hyp", "max_hook_deg": "Hook", "root_angle_120h_deg": "RootAngle", "sherwood": "Sh"}
for sc, w in words.items():
    if sc not in summ:
        continue
    for f, fw in fields.items():
        v = summ[sc][f]
        nd = 2 if f in ("min_o2_surface_kpa", "min_o2_core_kpa", "sherwood") else (0 if f in ("root_len_120h_um", "hyp_len_120h_um", "max_hook_deg", "root_angle_120h_deg") else 1)
        if f == "peak_eth_headspace_ppb" or f == "peak_eth_internal_ppb":
            nd = 1 if v and float(v) < 100 else 0
        if f == "hypoxic_frac_24h":
            v = str(float(v) * 100) if v not in ("", None) else v
            nd = 0
        put(f"{w}{fw}", num(v, nd))

cal = {r["metric"]: r["value"] for r in rows("calibration_metrics.csv")}  # current parameter set
fit = json.loads((ROOT / "data/calibration/fit_result.json").read_text())
put("FitLoss", f"{fit['loss']:.2f}")
put("FitNFree", str(len(fit["fitted"])))
put("FitNTargets", str(len(fit["targets"])))
for k, w in [("aba_12h_ratio", "AbaRatio"), ("testa_rupture_h", "FitTR"), ("endosperm_rupture_h", "FitER"), ("expansion_onset_h", "FitOnset"),
             ("peak_expansion_index", "FitPeak"), ("cap_strength_ratio_at_rupture", "FitCap")]:
    put(w, num(cal[k], 2 if k in ("aba_12h_ratio", "cap_strength_ratio_at_rupture") else (0 if k == "peak_expansion_index" else 1)))
fs = json.loads((ROOT / "data/calibration/fit_seedling.json").read_text())
put("SeedFitLoss", f"{fs['loss']:.2f}")
put("SeedFitNFree", str(len(fs["fitted"])))
for k, w in [("cot_emerged_h", "SfCotOut"), ("cot_open_h", "SfCotOpen"), ("hyp_max_rate_dark_mm_d", "SfHypDark"),
             ("hyp_max_rate_light_mm_d", "SfHypLight"), ("root_rate_120h_um_h", "SfRoot"), ("eth_prod_pl_h", "SfEth")]:
    put(w, num(cal[k], 2 if "mm_d" in k or "pl_h" in k else 0))

pops = {r["scenario"]: r for r in rows("population_summary.csv")}
pw = {"ground": "PopGround", "BRIC-PDFU 0 g": "PopBric", "56.5 kPa air (hypoxic)": "PopCounter", "water stress -0.4 MPa": "PopWater"}
for sc, w in pw.items():
    if sc in pops:
        put(f"{w}Tfifty", num(pops[sc]["t50_h"], 1))
        put(f"{w}Spread", num(pops[sc]["u8416_h"], 1))
        put(f"{w}Gmax", num(float(pops[sc]["gmax"]) * 100, 0))
        put(f"{w}N", pops[sc]["n"])
        put(f"{w}HydTfifty", num(pops[sc]["hydrotime_t50_h"], 1))
        put(f"{w}HydSpread", num(pops[sc]["hydrotime_u8416_h"], 1))

hyd = {round(float(r["psi_mpa"]), 2): r for r in rows("hydrotime_check.csv")}
for psi, tag in [(0.0, "Zero"), (-0.25, "Quarter"), (-0.4, "Forty"), (-0.55, "FiftyFive"), (-0.85, "EightyFive")]:
    r = hyd[psi]
    put(f"Hyd{tag}Model", num(r["model_endosperm_rupture_h"], 1) if r["model_endosperm_rupture_h"] else "none by 200")
    put(f"Hyd{tag}Theory", num(r["hydrotime_t50_h"], 1))

st = {r["scenario"]: r for r in rows("exposure_vs_decoder_stats.csv")}
for sc, w in [("bric_pdfu", "Bric"), ("ground_counterfactual", "Counter")]:
    if sc in st:
        put(f"Rho{w}", num(st[sc]["spearman_rho"], 2))
        put(f"Pval{w}", num(st[sc]["p_value"], 2))
        put(f"NClust{w}", st[sc]["n_clusters"])

air = rows("seed_air_speed.csv")
for r in air:
    if float(r["gravity_g"]) == 0:
        w = {"0.25": "Low", "0.5": "Mid", "0.85": "High"}[r["pump_l_min"]]
        put(f"GbcU{w}", num(float(r["u_seed_m_s"]) * 1000, 3))
        put(f"GbcMass{w}", num(r["outflow_over_inflow"], 2))

ts = rows("timeseries_bric_pdfu.csv")
put("BricHsStart", num(ts[0]["o2_hs_kpa"], 1))
put("BricHsEnd", num(ts[-1]["o2_hs_kpa"], 1))

gates = rows("gates_report.csv")
put("NGates", str(len(gates)))
put("NGatesPassed", str(sum(1 for g in gates if g["status"] == "PASS")))

tiers = {r["tier"]: r["n"] for r in rows("ledger_tiers.csv")}
for t_ in ("measured", "standard", "derived", "fitted", "assumed"):
    put(f"Tier{t_.capitalize()}", tiers.get(t_, "0"))
put("TierTotal", str(sum(int(v) for v in tiers.values())))

(M / "numbers.tex").write_text("% GENERATED by python/build_manuscript_inputs.py - do not edit\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in sorted(macros.items())))

# ---- bibliography
def tex(s: str) -> str:
    return (s.replace("′", "'").replace("\\", "/").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#").replace("$", "\\$"))


def bibkey(k):
    return re.sub(r"[^a-z0-9]", "", k.lower())


out = []
with (ROOT / "data/params/references.csv").open() as fh:
    for r in csv.DictReader(fh):
        if not r["doi"]:
            out.append(f"@misc{{{bibkey(r['key'])},\n  author = {{{tex(r['authors'])}}},\n  title = {{{tex(r['title'])}}},\n  note = {{{tex(r['journal'])}. {tex(r['verified_via'])}}}\n}}\n")
            continue
        authors = " and ".join(tex(a.strip()) for a in r["authors"].split(", "))
        out.append(
            f"@article{{{bibkey(r['key'])},\n  author = {{{authors}}},\n  title = {{{{{tex(r['title'])}}}}},\n  journal = {{{tex(r['journal'])}}},\n"
            f"  year = {{{r['year']}}},\n  volume = {{{r['volume']}}},\n  number = {{{r['issue']}}},\n  pages = {{{r['pages'].replace('-', '--')}}},\n  doi = {{{r['doi']}}}\n}}\n"
        )
(M / "references.bib").write_text("% GENERATED from data/params/references.csv (Crossref-verified) - do not edit\n" + "\n".join(out))
print(f"wrote {len(macros)} macros and {len(out)} references")
